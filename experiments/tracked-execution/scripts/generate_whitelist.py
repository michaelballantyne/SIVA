#!/usr/bin/env python3
"""Generate a whitelist coverage report for tracked-execution proxy dispatch.

This script introspects PyVista and numpy to produce a report showing:
- All public methods/properties on key PyVista classes and numpy.ndarray
- Which ones are currently in the whitelist
- Which ones are in the blacklist
- Which ones are uncovered (not in either)
- Suggested categorization of uncovered methods

Usage:
    python3 experiments/tracked-execution/scripts/generate_whitelist.py
"""

import inspect
import sys
from pathlib import Path

# Add the tracked-execution package to the path
TRACKED_EXEC_DIR = Path(__file__).parent.parent
sys.path.insert(0, str(TRACKED_EXEC_DIR))

import numpy as np

try:
    import pyvista as pv
    _PYVISTA_AVAILABLE = True
except ImportError:
    _PYVISTA_AVAILABLE = False
    print("ERROR: pyvista not available", file=sys.stderr)
    sys.exit(1)

from tracked_execution.whitelist import WHITELIST, BLACKLIST


# ---------------------------------------------------------------------------
# Heuristics for auto-categorization
# ---------------------------------------------------------------------------

# Method name substrings -> blacklist (filesystem/destructive ops)
_BLACKLIST_KEYWORDS = {
    "save", "write", "export", "delete", "remove", "close", "open",
    "dump", "unlink", "rmdir", "mkdir", "rename", "move",
}

# Method name substrings -> needs review (possible I/O / side effects)
_REVIEW_KEYWORDS = {
    "plot", "display", "show", "render", "draw", "view",
    "interact", "add_mesh", "add_points", "add_lines",
}


def _categorize(name: str) -> str:
    """Heuristically categorize an uncovered method name.

    Returns one of: 'safe', 'review', 'blacklist'
    """
    lower = name.lower()
    for kw in _BLACKLIST_KEYWORDS:
        if kw in lower:
            return "blacklist"
    for kw in _REVIEW_KEYWORDS:
        if kw in lower:
            return "review"
    return "safe"


# ---------------------------------------------------------------------------
# Collect public members for each class
# ---------------------------------------------------------------------------

def _get_public_members(cls) -> list[str]:
    """Return sorted list of public members defined on or inherited by cls."""
    return sorted(
        name for name in dir(cls)
        if not name.startswith("_")
    )


def _get_own_public_members(cls, base_cls=None) -> list[str]:
    """Return public members that are *defined* on cls (not inherited from base_cls)."""
    if base_cls is None:
        return _get_public_members(cls)
    base_members = set(dir(base_cls))
    return sorted(
        name for name in dir(cls)
        if not name.startswith("_") and name not in base_members
    )


# Classes to analyze
CLASSES = []

if _PYVISTA_AVAILABLE:
    CLASSES += [
        ("pv.DataSet", pv.DataSet, None),
        ("pv.PolyData", pv.PolyData, pv.DataSet),
        ("pv.UnstructuredGrid", pv.UnstructuredGrid, pv.DataSet),
        ("pv.ImageData", pv.ImageData, pv.DataSet),
        ("pv.StructuredGrid", pv.StructuredGrid, pv.DataSet),
    ]

CLASSES.append(("np.ndarray", np.ndarray, None))


# ---------------------------------------------------------------------------
# Build the report
# ---------------------------------------------------------------------------

def analyze_class(label: str, cls, base_cls) -> dict:
    """Analyze a class against the whitelist/blacklist."""
    if base_cls is not None:
        members = _get_public_members(cls)
        own_members = _get_own_public_members(cls, base_cls)
    else:
        members = _get_public_members(cls)
        own_members = members

    result = {
        "label": label,
        "cls": cls,
        "all_members": members,
        "own_members": own_members,
        "whitelisted": [],
        "blacklisted": [],
        "uncovered": {"safe": [], "review": [], "blacklist": []},
    }

    for name in members:
        key = (cls, name)
        if key in WHITELIST:
            result["whitelisted"].append(name)
        elif key in BLACKLIST:
            result["blacklisted"].append(name)
        else:
            cat = _categorize(name)
            result["uncovered"][cat].append(name)

    return result


def format_report(analyses: list[dict]) -> str:
    """Format the full coverage report as Markdown."""
    lines = []
    lines.append("# Whitelist Coverage Report")
    lines.append("")
    lines.append(
        "Auto-generated by `experiments/tracked-execution/scripts/generate_whitelist.py`."
    )
    lines.append("")
    lines.append(
        "Shows which public methods/properties on key PyVista and numpy classes "
        "are covered by the whitelist/blacklist, and which are uncovered."
    )
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Class | Total public | Whitelisted | Blacklisted | Uncovered safe | Uncovered review | Uncovered blacklist |")
    lines.append("|-------|-------------|-------------|-------------|----------------|-----------------|---------------------|")

    for a in analyses:
        n_safe = len(a["uncovered"]["safe"])
        n_review = len(a["uncovered"]["review"])
        n_bl = len(a["uncovered"]["blacklist"])
        lines.append(
            f"| `{a['label']}` "
            f"| {len(a['all_members'])} "
            f"| {len(a['whitelisted'])} "
            f"| {len(a['blacklisted'])} "
            f"| {n_safe} "
            f"| {n_review} "
            f"| {n_bl} |"
        )

    lines.append("")
    lines.append("## Categorization heuristics")
    lines.append("")
    lines.append("- **Safe (auto-add)**: Pure computational methods, read-only properties, "
                 "string representations. No I/O or mutation keywords detected.")
    lines.append("- **Needs review**: Names containing `plot`, `display`, `show`, `render`, "
                 "`draw`, `view`, `interact`, `add_mesh`, etc. May open windows or have "
                 "side effects.")
    lines.append("- **Should blacklist**: Names containing `save`, `write`, `export`, "
                 "`delete`, `remove`, `dump`, etc. Filesystem/destructive operations.")
    lines.append("")

    for a in analyses:
        lines.append(f"## `{a['label']}`")
        lines.append("")

        lines.append(f"**Total public members:** {len(a['all_members'])}")
        lines.append("")

        lines.append(f"### Whitelisted ({len(a['whitelisted'])})")
        lines.append("")
        if a["whitelisted"]:
            lines.append(", ".join(f"`{m}`" for m in sorted(a["whitelisted"])))
        else:
            lines.append("_(none)_")
        lines.append("")

        lines.append(f"### Blacklisted ({len(a['blacklisted'])})")
        lines.append("")
        if a["blacklisted"]:
            lines.append(", ".join(f"`{m}`" for m in sorted(a["blacklisted"])))
        else:
            lines.append("_(none)_")
        lines.append("")

        for cat, display in [
            ("safe", "Uncovered — Safe (auto-add)"),
            ("review", "Uncovered — Needs review"),
            ("blacklist", "Uncovered — Should blacklist"),
        ]:
            items = a["uncovered"][cat]
            lines.append(f"### {display} ({len(items)})")
            lines.append("")
            if items:
                lines.append(", ".join(f"`{m}`" for m in sorted(items)))
            else:
                lines.append("_(none)_")
            lines.append("")

    return "\n".join(lines)


def main():
    analyses = [analyze_class(label, cls, base_cls) for label, cls, base_cls in CLASSES]

    report = format_report(analyses)

    # Write to file
    output_path = TRACKED_EXEC_DIR / "meta" / "whitelist-coverage.md"
    output_path.write_text(report)
    print(f"Report written to {output_path}", file=sys.stderr)

    # Also print to stdout
    print(report)

    # Print a quick console summary
    print("\n" + "=" * 60, file=sys.stderr)
    print("COVERAGE SUMMARY", file=sys.stderr)
    print("=" * 60, file=sys.stderr)
    for a in analyses:
        n_safe = len(a["uncovered"]["safe"])
        n_review = len(a["uncovered"]["review"])
        n_bl = len(a["uncovered"]["blacklist"])
        print(
            f"{a['label']:30s}  WL={len(a['whitelisted']):3d}  BL={len(a['blacklisted']):3d}"
            f"  uncov safe={n_safe:3d}  review={n_review:3d}  blacklist={n_bl:3d}",
            file=sys.stderr,
        )

    # Print all "safe" uncovered for quick reference
    print("\n--- Uncovered SAFE methods (candidates to add) ---", file=sys.stderr)
    for a in analyses:
        safe = sorted(a["uncovered"]["safe"])
        if safe:
            print(f"\n{a['label']}:", file=sys.stderr)
            for i in range(0, len(safe), 8):
                print("  " + ", ".join(safe[i:i+8]), file=sys.stderr)


if __name__ == "__main__":
    main()
